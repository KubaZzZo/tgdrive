def clean_channel_name(name: str, extension: str = "") -> str:
    name = re.sub(r"[\\/\x00-\x1f]", "_", name).strip(" .")
    if extension and name.lower().endswith(extension.lower()):
        name = name[: -len(extension)].rstrip(" .")
    if not name:
        return ""
    return name[: 255 - len(extension)].rstrip(" .") + extension


def caption_title(caption: str) -> str:
    """Use the first descriptive paragraph; skip standalone links and tags."""
    lines: list[str] = []
    for line in caption.splitlines():
        line = line.strip()
        if not line:
            if lines:
                break
            continue
        if re.fullmatch(r"(?:(?:https?://\S+|@\S+|#\S+)\s*)+", line):
            continue
        lines.append(line)
    return " ".join(" ".join(lines).split())


def message_version(message: Any) -> datetime:
    return (message.edit_date or message.date or datetime.now(UTC)).astimezone(UTC)


def describe_message(
    message: Any, album_messages: list[Any] | None = None
) -> dict[str, Any] | None:
    if (getattr(message, "message", "") or "").startswith("tgdrive:v1:"):
        return None
    if not isinstance(getattr(message, "media", None), (MessageMediaDocument, MessageMediaPhoto)):
        return None
    file = message.file
    if not file:
        return None
    media = message.document or message.photo
    size = file.size
    if message.photo:
        # Match Telethon iter_download's selected (last) photo size exactly.
        sizes = getattr(message.photo, "sizes", [])
        if not sizes:
            return None
        photo_size = sizes[-1]
        size = (
            getattr(photo_size, "size", 0)
            or max(getattr(photo_size, "sizes", []) or [0])
            or len(getattr(photo_size, "bytes", b""))
        )
    if not size or size <= 0:
        return None
    name = (
        file.name or f"{'照片' if message.photo else '频道文件'}_{message.id}{file.ext or '.bin'}"
    )
    original_name = clean_channel_name(name) or f"文件_{message.id}.bin"
    caption = own_caption = getattr(message, "message", "") or ""
    version = message_version(message)
    group = getattr(message, "grouped_id", None)
    if group and album_messages:
        members = [m for m in album_messages if getattr(m, "grouped_id", None) == group]
        if not caption_title(caption):
            captions = {
                caption_title(m.message or ""): m.message
                for m in members
                if caption_title(m.message or "")
                and not (m.message or "").startswith("tgdrive:v1:")
            }
            # Only an unambiguous shared caption is inherited. A video's own
            # caption always wins; neighboring unrelated posts are never used.
            if len(captions) == 1:
                caption = next(iter(captions.values()))
    mime = effective_mime(original_name, file.mime_type)
    title = caption_title(caption) if mime.startswith("video/") else ""
    # Kept for adopting names generated by the previous numeric-filename rule.
    legacy_eligible = mime.startswith("video/") and (
        not file.name
        or re.fullmatch(r"(?:\d+|video[_ -]?\d*|频道文件_\d+)\.[^.]+", original_name, re.I)
    )
    legacy_title = (
        next(
            (
                line.strip()
                for line in own_caption.strip().splitlines()
                if line.strip() and not line.strip().startswith(("http://", "https://", "@", "#"))
            ),
            "",
        )
        if legacy_eligible
        else ""
    )
    extension = PurePath(original_name).suffix or file.ext or ".mp4"
    name = (clean_channel_name(title, extension) if title else original_name) or original_name
    date = message.date or datetime.now(UTC)
    return {
        "name": name,
        "original_name": original_name,
        "legacy_name": clean_channel_name(legacy_title, extension)
        if legacy_title
        else original_name,
        "size": int(size),
        "mime": effective_mime(name, file.mime_type),
        "media_key": f"{'document' if message.document else 'photo'}:{media.id}",
        "remote_version": version.isoformat(),
        "created_at": date.astimezone(UTC).isoformat(),
    }


def describe_bot_post(post: dict) -> tuple[dict, str] | None:
    caption = post.get("caption", "")
    if caption.startswith("tgdrive:v1:"):
        return None
    media_types = {
        "video": "video/mp4",
        "animation": "video/mp4",
        "audio": "audio/mpeg",
        "voice": "audio/ogg",
        "video_note": "video/mp4",
        "document": "application/octet-stream",
    }
    for kind, mime_type in media_types.items():
        if media := post.get(kind):
            default_mime = mime_type
            break
    else:
        photos = post.get("photo") or []
        if not photos:
            return None
        media = photos[-1]
        default_mime = "image/jpeg"

    size, file_id = media.get("file_size"), media.get("file_id")
    if not isinstance(size, int) or size <= 0 or not file_id:
        return None
    mid = post["message_id"]
    suffix = {"video/mp4": ".mp4", "audio/mpeg": ".mp3", "audio/ogg": ".ogg", "image/jpeg": ".jpg"}
    name = clean_channel_name(
        media.get("file_name") or f"频道文件_{mid}{suffix.get(default_mime, '.bin')}", ""
    )
    name = name or f"频道文件_{mid}"
    mime = effective_mime(name, media.get("mime_type") or default_mime)
    title = caption_title(caption) if mime.startswith("video/") else ""
    date = datetime.fromtimestamp(post["date"], UTC).isoformat()
    return {
        "name": clean_channel_name(title, PurePath(name).suffix or ".mp4") or name
        if title
        else name,
        "original_name": name,
        "size": size,
        "mime": mime,
        "media_key": f"bot:{media.get('file_unique_id') or file_id}",
        "remote_version": date,
        "created_at": date,
    }, file_id


class ChannelSyncService:
    def __init__(self, db: Database, storage: TelegramStorage, settings: Settings):
        self.db, self.storage, self.settings = db, storage, settings
        self._worker: asyncio.Task[None] | None = None
        self._wake = asyncio.Event()
        self._full = True
        self._unsubscribe = None
        self._album_lock = asyncio.Lock()
        self._albums: OrderedDict[int, list[Any]] = OrderedDict()
        token = settings.tg_bot_fallback_token
        self.bot = TelegramBot(token) if token else None
        self.bot_state: str | None = None
        self.bot_error: str | None = None
        self.state = "disabled" if not settings.channel_sync_enabled else "unavailable"
        self.running = False
        self.scanned = 0
        self.progress: int | None = None
        self._retry_at = 0.0
        self.imported = 0
        self.revision = 0
        self.last_error: str | None = None
        self.last_success: str | None = None

    @property
    def chat_id(self) -> str:
        return str(self.storage.chat)

    async def start(self) -> None:
        if not self.settings.channel_sync_enabled:
            return
        storage_status = self.storage.status()
        if storage_status.get("auth_required"):
            self.state = "auth_required"
            self.last_error = storage_status["error"]
            self._start_bot()
            return
        if not storage_status["connected"] or not hasattr(self.storage, "subscribe_channel"):
            self.state = "unavailable"
            self._start_bot()
            return
        self._unsubscribe = await self.storage.subscribe_channel(
            self.on_message, self.on_edit, self.on_delete
        )
        self.state = "idle"
        self._wake.set()
        self._worker = asyncio.create_task(self._loop(), name="channel-sync")

    def request_scan(self, full: bool = False) -> bool:
        if self.bot_state or not self._worker or self._worker.done():
            return False
        if self.running and not full:
            return False
        self._full = self._full or full
        self._wake.set()
        return True

    def _start_bot(self) -> None:
        if self.bot:
            self.bot_state = "connecting"
            self._worker = asyncio.create_task(self._poll_bot(self.bot), name="channel-sync-bot")

    async def _poll_bot(self, bot: TelegramBot) -> None:
        self.bot_state = "connecting"
        chat = self.storage.chat
        if not isinstance(chat, int) or chat >= 0:
            self.bot_state = "error"
            self.bot_error = "备用 Bot 需要原存储频道的数字 ID，请检查 TG_CHAT_ID。"
            return
        offset = None
        verified_until = 0.0
        while True:
            try:
                if time.monotonic() >= verified_until:
                    await bot.check_channel(chat)
                    verified_until = time.monotonic() + 300
                updates = await bot.updates(offset)
                self.bot_state = "listening"
                self.bot_error = None
                offset = None  # The server has confirmed the previous batch.
                for update in updates:
                    post = update.get("channel_post") or {}
                    if post.get("chat", {}).get("id") == chat:
                        self._ingest_bot_post(bot, post)
                    offset = update["update_id"] + 1
            except BotAPIError as exc:
                self.bot_state = "error"
                self.bot_error = str(exc)
                await asyncio.sleep(max(5, exc.retry_after))
            except Exception as exc:
                self.bot_state = "error"
                self.bot_error = "备用 Bot 收录失败，稍后重试。"
                logger.warning("Bot channel import failed (%s)", type(exc).__name__)
                await asyncio.sleep(5)

    def _ingest_bot_post(self, bot: TelegramBot, post: dict) -> None:
        described = describe_bot_post(post)
        if described:
            file, file_id = described
            mid = int(post["message_id"])
            if self.db.import_bot_file(self.chat_id, mid, file, bot.id, file_id):
                self.revision += 1
                self.imported += 1

    def ingest(
        self, message: Any, scan_run: str | None = None, album_messages: list[Any] | None = None
    ) -> bool:
        file = describe_message(message, album_messages)
        if not file:
            return False
        changed = self.db.import_channel_file(self.chat_id, int(message.id), file, scan_run)
        if changed:
            self.storage.invalidate_message(int(message.id))
            self.revision += 1
            self.imported += 1
        return changed

    async def album_context(self, message: Any) -> list[Any]:
        group = getattr(message, "grouped_id", None)
        if not group or not hasattr(self.storage, "get_album_messages"):
            return [message]
        async with self._album_lock:
            members = await self.storage.get_album_messages(message)
            by_id = {m.id: m for m in members if getattr(m, "grouped_id", None) == group}
            # Serialize metadata reads and retain newer live edits for members
            # still present. Missing members are not retained after deletion.
            for previous in self._albums.get(group, []):
                current = by_id.get(previous.id)
                if current and message_version(previous) > message_version(current):
                    by_id[previous.id] = previous
            existing = by_id.get(message.id)
            if not existing or message_version(message) >= message_version(existing):
                by_id[message.id] = message
            result = sorted(by_id.values(), key=lambda m: m.id)
            self._albums[group] = result
            self._albums.move_to_end(group)
            if len(self._albums) > 32:
                self._albums.popitem(last=False)
            return result

    async def on_message(self, message: Any) -> None:
        try:
            members = await self.album_context(message)
            for member in members:
                self.ingest(member, album_messages=members)
        except FloodWaitError as exc:
            if self.state != "auth_required":
                self._defer_rpc(exc)
                self.request_scan(full=True)
        except Exception as exc:
            if self.state == "auth_required":
                return
            logger.exception("Could not import channel message")
            self.last_error = str(exc)
            self._full = True
            self._wake.set()

    async def on_edit(self, message: Any) -> None:
        if describe_message(message):
            await self.on_message(message)
        else:
            await self.on_delete([int(message.id)])

    async def on_delete(self, ids: list[int]) -> None:
        for mid in ids:
            self.storage.invalidate_message(mid)
        removed = self.db.remove_channel_messages(self.chat_id, ids)
        self.revision += removed
        for group, members in list(self._albums.items()):
            remaining = [m for m in members if m.id not in ids]
            if len(remaining) != len(members):
                self._albums[group] = remaining
                for member in remaining:
                    self.ingest(member, album_messages=remaining)
        if removed:
            # Deleted caption-bearing members may belong to older albums that
            # have left the bounded memory cache; a full scan repairs those too.
            self._full = True
            self._wake.set()

    def _defer_rpc(self, exc: FloodWaitError) -> None:
        self._retry_at = max(self._retry_at, time.monotonic() + max(1, exc.seconds))

    async def _wait_for_rate_limit(self) -> None:
        while (remaining := self._retry_at - time.monotonic()) > 0:
            self.state = "rate_limited"
            await asyncio.sleep(remaining)
        self.state = "syncing"

    async def _scan_rpc(self, operation: Callable[[], Awaitable[T]]) -> T:
        while True:
            await self._wait_for_rate_limit()
            try:
                return await operation()
            except FloodWaitError as exc:
                self._defer_rpc(exc)

    async def _scan_history(self, cursor: int, max_id: int) -> AsyncIterator[Any]:
        while True:
            await self._wait_for_rate_limit()
            try:
                async for message in self.storage.iter_channel_messages(cursor, max_id):
                    yield message
                    cursor = int(message.id)
                return
            except FloodWaitError as exc:
                self._defer_rpc(exc)

    async def scan(self, full: bool = False) -> None:
        self.running = True
        self.state = "syncing"
        self.scanned = 0
        self.progress = None
        self.last_error = None
        generation = uuid.uuid4().hex if full else None
        try:
            max_id = max(
                await self._scan_rpc(self.storage.latest_channel_message_id),
                self.db.channel_cursor(self.chat_id),
                self.db.channel_high_water(self.chat_id),
            )
            cursor = 0 if full else self.db.channel_cursor(self.chat_id)
            self.progress = 0
            albums: OrderedDict[int, list[Any]] = OrderedDict()
            async for message in self._scan_history(cursor, max_id):
                group = getattr(message, "grouped_id", None)
                members = None
                if group:
                    if group not in albums or group not in self._albums:
                        albums[group] = await self._scan_rpc(partial(self.album_context, message))
                        if len(albums) > 32:
                            albums.popitem(last=False)
                    members = self._albums.get(group, albums[group])
                    cached = next((m for m in members if m.id == message.id), None)
                    if not cached or message_version(message) > message_version(cached):
                        members = [m for m in members if m.id != message.id] + [message]
                        self._albums[group] = members
                        albums[group] = members
                        for member in members:
                            if member.id <= max_id:
                                self.ingest(member, generation, members)
                current = next((m for m in members or [] if m.id == message.id), message)
                self.ingest(current, generation, members)
                message_id = int(message.id)
                self.db.advance_channel_cursor(self.chat_id, message_id)
                self.scanned += 1
                if max_id > cursor:
                    self.progress = min(99, (message_id - cursor) * 100 // (max_id - cursor))
                if self.scanned % 100 == 0:
                    await asyncio.sleep(0)
            if full:
                self.revision += self.db.reconcile_channel(self.chat_id, generation, max_id)
            self.db.advance_channel_cursor(self.chat_id, max_id)
            self.progress = 100
            self.last_success = datetime.now(UTC).isoformat()
            self.state = "idle"
        except SESSION_AUTH_ERRORS as exc:
            self.storage.invalidate_session()
            self.state = "auth_required"
            self.last_error = self.storage.error
            self._wake.clear()
            if self._unsubscribe:
                self._unsubscribe()
                self._unsubscribe = None
            logger.warning("Telegram rejected the channel sync session: %s", exc)
            raise
        except Exception as exc:
            self.state = "error"
            self.last_error = str(exc)
            logger.exception("Channel synchronization failed")
            raise
        finally:
            self.running = False

    async def _loop(self) -> None:
        while True:
            try:
                await asyncio.wait_for(
                    self._wake.wait(), timeout=self.settings.channel_sync_interval
                )
            except TimeoutError:
                pass
            self._wake.clear()
            full, self._full = self._full, False
            try:
                await self.scan(full)
            except asyncio.CancelledError:
                raise
            except SESSION_AUTH_ERRORS:
                if self.bot:
                    await self._poll_bot(self.bot)
                return
            except Exception:
                self._full = self._full or full

    async def shutdown(self) -> None:
        if self._unsubscribe:
            self._unsubscribe()
        if self._worker:
            self._worker.cancel()
            await asyncio.gather(self._worker, return_exceptions=True)
        self.bot_state = None
        self.bot_error = None
        self.state = "stopped"

    def status(self) -> dict[str, Any]:
        return {
            "enabled": self.settings.channel_sync_enabled,
            "state": self.state,
            "running": self.running or self._wake.is_set(),
            "scanned": self.scanned,
            "progress": self.progress,
            "retry_after": max(0, ceil(self._retry_at - time.monotonic()))
            if self.state == "rate_limited"
            else None,
            "imported": self.imported,
            "files": self.db.channel_file_count(self.chat_id),
            "revision": self.revision,
            "last_success": self.last_success,
            "error": self.last_error,
            "bot_state": self.bot_state,
            "bot_error": self.bot_error,
            "interval": self.settings.channel_sync_interval,
        }
